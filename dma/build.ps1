# Builds the EktaHR DMA exes (no .NET SDK needed - uses the C# compiler that ships with Windows).
#
#   EktaHR-Agent.exe         employee PCs. Production builds are also written to agent\publish - the
#                            copy every DMA server hands out (Download Agent button + auto-update).
#   EktaHR-AdminConsole.exe  admin PCs. Office server + web console + Node + agent packed inside.
#
# Everything a release changes is in dma\dma.config.json:
#   environment          production / development (EktaHR login service, online server, database use)
#   agentVersion         raise for every new agent (auto-update installs only higher versions)
#   adminConsoleVersion  raise for every new Admin Console
#
# Usage (PowerShell, from the dma folder):
#   powershell -ExecutionPolicy Bypass -File .\build.ps1                       # agent + Admin Console, as in dma.config.json
#   powershell -ExecutionPolicy Bypass -File .\build.ps1 -AgentOnly            # agent only
#   powershell -ExecutionPolicy Bypass -File .\build.ps1 -Env development      # other environment than the config file
#   powershell -ExecutionPolicy Bypass -File .\build.ps1 -Release EktaHR-DMA-20261105
#
# Output: release\<Release>\  (default EktaHR-DMA-<today>, or EktaHR-DMA-<today>-<env> for non-production).
# Then push and run `git pull` on the online server so it hands out the new agent.

param(
  [Alias('Env')][string]$Environment = "",
  [string]$Release = "",
  [switch]$AgentOnly
)

$ErrorActionPreference = 'Stop'
$dma = $PSScriptRoot
$csc = Join-Path $env:WINDIR "Microsoft.NET\Framework64\v4.0.30319\csc.exe"

# ---- Release config (dma.config.json) -------------------------------------------------------
$config = Get-Content (Join-Path $dma "dma.config.json") -Raw | ConvertFrom-Json
if (-not $Environment) { $Environment = [string]$config.environment }
if (-not $Environment) { $Environment = "production" }
$Environment = $Environment.ToLower()
$settings = $config.environments.$Environment
if ($null -eq $settings) {
  throw "Unknown environment '$Environment' - defined in dma.config.json: $($config.environments.PSObject.Properties.Name -join ' / ')"
}
$agentVersion = [string]$config.agentVersion
$payloadVersion = [string]$config.adminConsoleVersion
foreach ($v in @(@('agentVersion', $agentVersion), @('adminConsoleVersion', $payloadVersion))) {
  if ($v[1] -notmatch '^\d+(\.\d+){1,3}$' -or ($v[1].Split('.') | Where-Object { [int]$_ -gt 65535 })) {
    throw "dma.config.json: $($v[0]) '$($v[1])' must look like 1.2.3 or 2026.11.05.1 (numbers up to 65535)"
  }
}
$isProduction = $Environment -eq 'production'
if (-not $Release) { $Release = "EktaHR-DMA-" + (Get-Date -Format yyyyMMdd) + $(if ($isProduction) { "" } else { "-$Environment" }) }
$rel = Join-Path $dma "release\$Release"
New-Item -ItemType Directory -Force $rel | Out-Null
Write-Host "Environment: $Environment - logins via $($settings.hrmsApiUrl), online server: $(if ($settings.onlineServerUrl) { $settings.onlineServerUrl } else { 'none (office LAN only)' })"

function Invoke-Csc([string[]]$CscArgs, [string]$What) {
  $out = & $csc @CscArgs
  $out | Where-Object { $_ -notmatch 'warning CS' } | ForEach-Object { Write-Host $_ }
  if ($LASTEXITCODE -ne 0) { throw "$What build failed" }
}

function Copy-Built([string]$From, [string]$To) {
  try { Copy-Item $From $To -Force }
  catch { throw "Cannot write $To - is it running? Close it (tray icon > Exit) and build again." }
}

# File details shown in Windows (right-click the exe > Properties > Details): description, Comments
# (environment + build), file / product version, company. Compiled together with the exe's source.
$builtAt = Get-Date -Format 'yyyy-MM-dd HH:mm'
function New-AssemblyInfo([string]$Path, [string]$Title, [string]$Comments, [string]$Version) {
  $parts = @($Version.Split('.') | ForEach-Object { [int]$_ })
  while ($parts.Count -lt 4) { $parts += 0 }
  $fileVersion = ($parts[0..3] -join '.')
  $lines = @(
    "// Generated by build.ps1 - do not edit",
    "using System.Reflection;",
    "[assembly: AssemblyTitle(`"$Title`")]",
    "[assembly: AssemblyDescription(`"$Comments`")]",
    "[assembly: AssemblyCompany(`"EktaHR`")]",
    "[assembly: AssemblyProduct(`"EktaHR DMA`")]",
    "[assembly: AssemblyCopyright(`"Copyright (c) $((Get-Date).Year) EktaHR`")]",
    "[assembly: AssemblyVersion(`"$fileVersion`")]",
    "[assembly: AssemblyFileVersion(`"$fileVersion`")]",
    "[assembly: AssemblyInformationalVersion(`"$Version ($Environment)`")]"
  )
  [IO.File]::WriteAllText($Path, ($lines -join "`r`n") + "`r`n", (New-Object Text.UTF8Encoding($false)))
}
$onlineText = $(if ($settings.onlineServerUrl) { $settings.onlineServerUrl } else { 'none (office LAN only)' })

# ---- 1. Agent -------------------------------------------------------------------------------
Write-Host "Building agent $agentVersion ($Environment) ..."
# Version + environment values for the agent, compiled together with AgentSingle.cs
$buildEnvCs = Join-Path $env:TEMP "EktaHR-BuildEnv.cs"
$buildEnvLines = @(
  "// Generated by build.ps1 from dma\dma.config.json - do not edit",
  "namespace EktaDMAAgent",
  "{",
  "    static class BuildEnv",
  "    {",
  "        public const string AgentVersion = `"$agentVersion`";",
  "        public const string Name = `"$Environment`";",
  "        public const string HrmsApiUrl = `"$($settings.hrmsApiUrl)`";",
  "        public const string OnlineServerUrl = `"$($settings.onlineServerUrl)`";",
  "    }",
  "}"
)
[IO.File]::WriteAllText($buildEnvCs, ($buildEnvLines -join "`r`n") + "`r`n", (New-Object Text.UTF8Encoding($false)))
$agentInfoCs = Join-Path $env:TEMP "EktaHR-AgentInfo.cs"
New-AssemblyInfo $agentInfoCs "EktaHR Agent" `
  "EktaHR DMA desktop agent $agentVersion | $Environment | logins: $($settings.hrmsApiUrl) | online server: $onlineText | built $builtAt" `
  $agentVersion
$agentOut = Join-Path $env:TEMP "EktaHR-Agent-build.exe"
Push-Location (Join-Path $dma "agent")
try {
  Invoke-Csc @('-nologo', '-target:winexe', '-win32icon:ektaHr.ico', '-resource:ektaHr_icon_256.png,EktaHr.AppIcon.png',
    '-r:System.Windows.Forms.dll', '-r:System.Drawing.dll', '-r:Microsoft.VisualBasic.dll', "-out:$agentOut", 'AgentSingle.cs', $buildEnvCs, $agentInfoCs) 'Agent'
} finally { Pop-Location }
Copy-Built $agentOut (Join-Path $rel "EktaHR-Agent.exe")
if ($isProduction) {
  # The copy servers hand out and agents auto-update to - production builds only
  Copy-Built $agentOut (Join-Path $dma "agent\publish\EktaHR-Agent.exe")
  Write-Host "  agent $agentVersion -> agent\publish and release\$Release"
} else {
  Write-Host "  agent $agentVersion ($Environment) -> release\$Release  (agent\publish keeps the production agent)"
}
if ($AgentOnly) { return }

# ---- 2. Admin Console -----------------------------------------------------------------------
Write-Host "Building Admin Console (server payload $payloadVersion, $Environment) ..."

# Web console
Push-Location (Join-Path $dma "admin_console")
try {
  if (-not (Test-Path node_modules)) { npm ci; if ($LASTEXITCODE -ne 0) { throw "npm ci (admin_console) failed" } }
  npm run build; if ($LASTEXITCODE -ne 0) { throw "Web console build failed" }
} finally { Pop-Location }
$serverDir = Join-Path $dma "server"
if (-not (Test-Path (Join-Path $serverDir "node_modules"))) {
  Push-Location $serverDir
  try { npm ci --omit=dev; if ($LASTEXITCODE -ne 0) { throw "npm ci (server) failed" } } finally { Pop-Location }
}

# Payload layout (what AdminSingle.cs unpacks): admin_console\dist, agent\publish, node\node.exe, server\,
# dma.config.json (environments, read by server\src\config.js)
$stage = Join-Path $env:TEMP "ektahr-dma-payload"
if (Test-Path $stage) { Remove-Item -LiteralPath $stage -Recurse -Force }
New-Item -ItemType Directory -Force "$stage\admin_console", "$stage\agent\publish", "$stage\node", "$stage\server\storage\idle-logs", "$stage\server\storage\screenshots" | Out-Null
Copy-Item (Join-Path $dma "admin_console\dist") "$stage\admin_console\dist" -Recurse
Copy-Item $agentOut "$stage\agent\publish\EktaHR-Agent.exe"
Copy-Item (Get-Command node).Source "$stage\node\node.exe"
Copy-Item (Join-Path $dma "dma.config.json") "$stage\dma.config.json"
Copy-Item (Join-Path $serverDir "src") "$stage\server\src" -Recurse
Copy-Item (Join-Path $serverDir "package.json") "$stage\server\package.json"
Copy-Item (Join-Path $serverDir "node_modules") "$stage\server\node_modules" -Recurse

# Office server settings: the environment decides login service / online server / database;
# own random token secret per build
$secretBytes = New-Object byte[] 48
[Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($secretBytes)
$secret = -join ($secretBytes | ForEach-Object { '{0:x2}' -f $_ })
$envLines = @(
  "DMA_ENV=$Environment",
  "PORT=2005",
  "DMA_MODE=lan",
  "LAN_ONLY=true",
  "JWT_SECRET=$secret",
  "SCREENSHOT_RETENTION_DAYS=1",
  "IDLE_THRESHOLD_SECONDS=300",
  "# No MONGODB_URI on purpose: logins and the staff list go through the EktaHR backend."
)
[IO.File]::WriteAllText("$stage\server\.env", ($envLines -join "`r`n") + "`r`n", (New-Object Text.UTF8Encoding($false)))

Add-Type -AssemblyName System.IO.Compression.FileSystem
$zip = Join-Path $env:TEMP "EktaHR.DmaServer.zip"
if (Test-Path $zip) { Remove-Item -LiteralPath $zip -Force }
[IO.Compression.ZipFile]::CreateFromDirectory($stage, $zip, [IO.Compression.CompressionLevel]::Optimal, $false)

$adminInfoCs = Join-Path $env:TEMP "EktaHR-AdminInfo.cs"
New-AssemblyInfo $adminInfoCs "EktaHR Admin Console" `
  "EktaHR DMA admin console with built-in office server $payloadVersion | $Environment | logins: $($settings.hrmsApiUrl) | online server: $onlineText | agent $agentVersion inside | built $builtAt" `
  $payloadVersion
# Version stamp of the built-in office server (adminConsoleVersion), compiled together with AdminSingle.cs
$adminBuildCs = Join-Path $env:TEMP "EktaHR-AdminBuild.cs"
$adminBuildLines = @(
  "// Generated by build.ps1 from dma\dma.config.json - do not edit",
  "namespace EktaHR.AdminConsole",
  "{",
  "    static class AdminBuild",
  "    {",
  "        public const string PayloadVersion = `"$payloadVersion`";",
  "    }",
  "}"
)
[IO.File]::WriteAllText($adminBuildCs, ($adminBuildLines -join "`r`n") + "`r`n", (New-Object Text.UTF8Encoding($false)))
$adminOut = Join-Path $env:TEMP "EktaHR-AdminConsole-build.exe"
Push-Location (Join-Path $dma "admin_console")
try {
  Invoke-Csc @('-nologo', '-target:winexe', '-win32icon:public\ektaHr.ico', '-r:System.Windows.Forms.dll', '-r:System.Drawing.dll',
    '-r:System.IO.Compression.dll', '-r:System.IO.Compression.FileSystem.dll', "-resource:$zip,EktaHR.DmaServer.zip",
    "-out:$adminOut", 'AdminSingle.cs', $adminBuildCs, $adminInfoCs) 'Admin Console'
} finally { Pop-Location }
Copy-Built $adminOut (Join-Path $rel "EktaHR-AdminConsole.exe")
Remove-Item -LiteralPath $stage -Recurse -Force
Write-Host "  Admin Console (payload $payloadVersion, $Environment) -> release\$Release"
if ($isProduction) { Write-Host "Done. Push, then run 'git pull' on the online server so it hands out agent $agentVersion." }
else { Write-Host "Done ($Environment build - not for the production servers)." }
